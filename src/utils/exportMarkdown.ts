import { PlanGoal, HORIZONS } from '../types';
import { calculateEndTime, formatDuration } from './dateUtils';

export function exportTodayPlanToMarkdown(goals: PlanGoal[], dateStr: string): string {
  const dailyTasks = goals.filter((g) => g.horizon === 'daily' && (!g.date || g.date === dateStr));
  const hourlyTasks = goals.filter((g) => g.horizon === 'hourly' && (!g.date || g.date === dateStr));

  // Sort hourly by timeSlot
  hourlyTasks.sort((a, b) => (a.timeSlot || '00:00').localeCompare(b.timeSlot || '00:00'));

  const completedHourly = hourlyTasks.filter((t) => t.status === 'completed');
  const totalHourly = hourlyTasks.length;
  const progressPercent = totalHourly > 0 ? Math.round((completedHourly.length / totalHourly) * 100) : 0;

  let md = `# 📅 CascadePlan Daily Action Plan: ${dateStr}\n\n`;
  md += `> **Daily Progress:** ${progressPercent}% completed (${completedHourly.length}/${totalHourly} action blocks)\n\n`;

  // Daily Priorities
  md += `## 🎯 Daily Key Priorities\n\n`;
  if (dailyTasks.length === 0) {
    md += `*No high-level daily priorities set for today.*\n\n`;
  } else {
    for (const dt of dailyTasks) {
      const check = dt.status === 'completed' ? '[x]' : '[ ]';
      md += `- ${check} **${dt.title}** (${dt.progress}%)\n`;
      if (dt.description) {
        md += `  > ${dt.description.replace(/\n/g, '\n  > ')}\n`;
      }
    }
    md += `\n`;
  }

  // Hourly Timeline (06:00 to 23:00)
  md += `## ⏱️ Scheduled Time Blocks & Action Ranges\n\n`;
  const timeSlots = [
    '06:00', '07:00', '08:00', '09:00', '10:00', '11:00',
    '12:00', '13:00', '14:00', '15:00', '16:00', '17:00',
    '18:00', '19:00', '20:00', '21:00', '22:00', '23:00'
  ];

  for (const slot of timeSlots) {
    const slotTasks = hourlyTasks.filter((t) => t.timeSlot === slot);
    if (slotTasks.length > 0) {
      md += `### ${slot}\n`;
      for (const t of slotTasks) {
        const check = t.status === 'completed' ? '[x]' : '[ ]';
        const pomodoros = t.pomodoroCount ? ` 🍅 ${t.pomodoroCount}` : '';
        const duration = t.durationMinutes || 60;
        const endTime = t.endTime || calculateEndTime(slot, duration);
        const range = `\`${slot} - ${endTime} (${formatDuration(duration)})\``;
        const alarm = t.alarmEnabled ? ' 🔔' : '';

        md += `- ${check} ${range} **${t.title}**${alarm}${pomodoros}\n`;
        if (t.description) {
          md += `  ${t.description.replace(/\n/g, '\n  ')}\n`;
        }
      }
      md += `\n`;
    }
  }

  // Unscheduled tasks
  const unscheduled = hourlyTasks.filter((t) => !t.timeSlot);
  if (unscheduled.length > 0) {
    md += `### Unscheduled / Flexible Tasks\n`;
    for (const t of unscheduled) {
      const check = t.status === 'completed' ? '[x]' : '[ ]';
      md += `- ${check} ${t.title}\n`;
    }
    md += `\n`;
  }

  md += `---\n*Generated by CascadePlan - Offline-First Cascading Planner*\n`;
  return md;
}

export function exportFullCascadeToMarkdown(goals: PlanGoal[]): string {
  let md = `# 🌲 CascadePlan: Complete 8-Horizon Hierarchy\n\n`;
  md += `*Exported on: ${new Date().toLocaleString()}*\n\n`;

  const topGoals = goals.filter((g) => !g.parentId || g.horizon === 'yearly');

  function renderNode(goal: PlanGoal, depth: number) {
    const indent = '  '.repeat(depth);
    const horizonMeta = HORIZONS.find((h) => h.id === goal.horizon);
    const badge = horizonMeta ? `[${horizonMeta.shortLabel}]` : '';
    const check = goal.status === 'completed' ? '[x]' : '[ ]';

    md += `${indent}- ${check} ${badge} **${goal.title}** (${goal.progress}%)\n`;
    if (goal.description) {
      const descFirstLine = goal.description.split('\n')[0];
      if (descFirstLine) {
        md += `${indent}  > ${descFirstLine}\n`;
      }
    }

    // Children
    const children = goals.filter((g) => g.parentId === goal.id);
    for (const child of children) {
      renderNode(child, depth + 1);
    }
  }

  for (const root of topGoals) {
    renderNode(root, 0);
    md += `\n`;
  }

  return md;
}
